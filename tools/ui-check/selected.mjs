import { chromium } from "playwright-core";
const email = "admin@evechat.local";
const password = process.argv[2];
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
await page.goto("http://127.0.0.1:3000/login", { waitUntil: "networkidle" });
await page.fill("#email", email);
await page.fill("#password", password);
await page.click('button[type="submit"]');
await page.waitForURL("**/inbox");
await page.waitForTimeout(2500);
const row = page.getByText("Smoke Visitor").first();
console.log("conversation rows:", await page.getByText("Smoke Visitor").count());
await row.click();
await page.waitForTimeout(2000);
await page.screenshot({ path: "inbox-selected.png" });
const text = await page.locator("body").innerText();
console.log("has composer:", text.includes("???? ??? ?? ???????"));
console.log("has visitor block:", text.includes("??????? ?????") || text.includes("EVE"));
console.log("snippet:", text.replace(/\n+/g, " | ").slice(0, 400));
console.log("errors:", errors);
await browser.close();